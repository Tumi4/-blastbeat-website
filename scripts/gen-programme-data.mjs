/*!
 * Generates the PUBLIC assets/js/programme-data.js from the internal
 * data/programme-data.json.
 *
 * Why a generator exists
 *   /admin is a static page, so anything it loads client-side is publicly
 *   fetchable — no login gate applies to static assets. The internal JSON
 *   holds CRM-grade pipeline data (named third-party contacts, deal-stage
 *   notes, NDA mentions) that must NEVER ship in the public bundle.
 *   The launch audit (2026-07-03) found the full file deployed publicly;
 *   this generator is the fix. data/ is also blocked from the CDN via
 *   netlify.toml force-404 rules.
 *
 * What gets stripped for the public build
 *   - sponsor_pipeline  (named contacts, outreach status, NDA notes)
 *   - activity          (internal deal ledger)
 *   - school_groups     (relationship blurbs; unused by /admin)
 *   - _meta internal strategy notes
 *   - person names inside school/sponsor notes (explicit scrub maps below)
 *
 * Usage:  node scripts/gen-programme-data.mjs
 * The full unredacted JSON stays in data/ (repo + blocked from serving)
 * as the source of truth for the Trixta V2 hand-off.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('../data/programme-data.json', import.meta.url), 'utf8'));

// Explicit public rewrites — notes that named private individuals or
// carried deal-sensitive framing. Anything not listed passes through.
const SCHOOL_NOTES = {
  'camps-bay': 'Featured in the TV series',
  'wynberg': "Ran 'Sugar Mama Records'",
  'sacs': "Ran 'Guns Entertainment'",
  'zisukhanyo': 'Heritage community school',
  'blasc': 'Lead pilot · all three verticals',
  'rhodes': 'Founding licence school (Tekkers)',
  'camst': 'Active partner via Eduponics · aquaponics agri-hub',
  'windy': 'Proposal stage · not confirmed',
  'qondokuhle': 'Proposal stage · not confirmed',
  'king-shaka': 'Proposal stage · not confirmed',
  'mzimvubu': 'Proposal stage · not confirmed',
  'zimele': 'Proposal stage · not confirmed',
  'nam-d1': 'Agreed in principle · subject to Ministry of Education · target Mar–Apr 2026',
  'nam-d2': 'Agreed in principle',
  'nam-d3': 'Agreed in principle',
  'nam-d4': 'Agreed in principle',
};
const SPONSOR_OVERRIDES = {
  tekkers: { brand: 'Tekkers', note: 'Founding licence at R12,225 · Puma co-sponsor' },
  footbeat: { name: 'FootBeat', note: 'Lead pilot at BLASC Academy' },
  blackcoffee: { note: 'Proposal stage · subject to confirmation' },
};

const pub = {
  _meta: {
    title: src._meta.title,
    version: src._meta.version,
    updated: src._meta.updated,
    note: 'Public build — internal pipeline data stripped by scripts/gen-programme-data.mjs. Source of truth: data/programme-data.json (not served).',
  },
  org: src.org,
  pricing: src.pricing,
  issuing_entity_by_region: src.issuing_entity_by_region,
  schools: src.schools.map(s => ({ ...s, note: SCHOOL_NOTES[s.id] ?? s.note ?? '' })),
  sponsors: src.sponsors.map(s => ({ ...s, ...(SPONSOR_OVERRIDES[s.id] || {}) })),
  licences: src.licences,
  cohort_target: src.cohort_target,
  tiers: src.tiers,
  ambassadors: src.ambassadors,
};

const banner = `/*! BlastBeat V2 — canonical programme data (window.BB_PROGRAMME).
 * PUBLIC BUILD generated by scripts/gen-programme-data.mjs — internal
 * pipeline data (contacts, deal notes) is stripped here by design.
 * Do NOT hand-edit; edit data/programme-data.json and regenerate.
 * Owner: Tumelo Ncube (CTO).
 */
`;
writeFileSync(new URL('../assets/js/programme-data.js', import.meta.url),
  banner + 'window.BB_PROGRAMME = ' + JSON.stringify(pub, null, 2) + ';\n');
console.log('assets/js/programme-data.js regenerated (public build).');
const out = readFileSync(new URL('../assets/js/programme-data.js', import.meta.url), 'utf8');
